"""LONGER PERMUTATION CYCLES in the forwarder-thunk map rows (lane CJ-2).

WHAT LANE CI-2 LEFT, VERBATIM
-----------------------------
    "150 rows had a fitting existing name but only 4 were mutual, so the rest
     are ONE-DIRECTIONAL, meaning the correct name is IN USE ELSEWHERE => these
     are LONGER PERMUTATION CYCLES, not swaps. That is the obvious next lane."

CI-2 repaired 2 two-cycles (CharIKHead Load<->SetType, TrackPanelDir
Save<->Copy) and stopped.  This tool measures the cycle structure of the whole
population and extracts the repairs that fall out of it.

THE RELATION IS AT **METHOD** GRANULARITY, NOT MANGLED-NAME GRANULARITY
-----------------------------------------------------------------------
The first reconstruction attempted here matched WHOLE SYNTHESISED NAMES -- for
row A, find a map name N with synth(N) == A's dethunk target row.  It found
139 fitting names and **ZERO** mutual pairs on the pre-CI-2 map, i.e. it could
not reproduce CI-2's own two landed repairs.  The reason is instructive and is
the ICF-fold confound rtti_vtable_index documents:

    0x823c10a8  claims ?Load@CharIKHead@@$4...
                branches to ?SetType@**FlowTrigger**@@UAAXVSymbol@@@Z
    0x823c10f8  claims ?SetType@CharIKHead@@$4...
                branches to ?Load@CharIKHead@@UAAXAAVBinStream@@@Z

The pair is mutual in METHOD (Load <-> SetType) but NOT in mangled name: the
body A forwards to is an ICF fold representative the map names after a
DIFFERENT class (FlowTrigger).  A whole-name relation therefore cannot see the
very swap CI-2 landed.  CI-2's slot channel says the same thing from the other
side -- it "names the correct METHOD but a full mangled signature cannot be
synthesised".  So: match on sig_strict()[0], the method.

The second confirmation that class is the wrong key: CI-2's other landed pair is
?Save@TrackPanelDir**Base**@@ <-> ?Copy@TrackPanelDir@@ -- mutual in method with
the CLASSES DIFFERENT.  The gate that admits it is the home UNIT, not the class.

THE MODEL
---------
Within one pinned unit U, the thunk names are a bag of labels sitting on a bag
of addresses.  For row A let

    h(A) = method claimed by the name currently on A
    w(A) = method of the body A actually branches to  (branch channel)

A is correct iff h(A) == w(A).  A repair permutes the labels inside U so that
every row's h becomes its w.  Define the functional graph

    A -> B   iff B is the UNIQUE row in U with h(B) == w(A)

("B is holding the name A should have").  Then:

  * an AGREE row has h == w, so it maps to ITSELF -- a self-loop.  This is a
    structural safety property, not an assumption: under the uniqueness gate a
    correctly-named row can NEVER be dragged into a multi-row cycle, so no
    rotation this tool proposes can break a currently-correct row.
  * a cycle of length k >= 2 is a k-way rotation that repairs all k rows at once.
  * a node with no candidate, or with >= 2 candidates, is a BLOCKED chain end.

CONTROLS (each stated with the number that would have shown it failing)
----------------------------------------------------------------------
C1 POSITIVE, KNOWN ANSWER.  On the PRE-CI-2 map (481ecc8f^) the two pairs CI-2
   actually landed must come out as 2-cycles.  A relation that cannot reproduce
   an already-landed repair is not measuring the same thing.
C2 SELF-LOOP FLOOR.  The AGREE population is the false-positive floor: those
   rows are known-good, so the relation must return the row ITSELF.  A relation
   that scatters AGREE rows into foreign cycles is noise.
C3 FAIL ON DEMAND.  Shuffle the thunk names WITHIN each unit (the exact swap
   objdiff cannot see -- report.rs:394 masks reloc args) and the self-loop rate
   must COLLAPSE.  If it does not, the relation is fitting noise.
C4 ADJUSTMENT GATE (independent second channel, CF-8).  A rotation moves a name
   onto a new address; the name's `$4PPPPPPPM@<adj>@` field must equal that
   address's own `addi`-derived adjustment.  The branch channel is structurally
   blind to displacement, so this is genuinely independent of how the cycle was
   found.
C5 RTTI VERIFICATION.  Candidates here are generated by the BRANCH channel, so
   the independent verifier is the RTTI oracle (ancestry + vtable-family slot
   consensus).  This is the exact REVERSE of CI-2, which generated with RTTI and
   verified with branch.  Using the generating instrument to verify is circular
   and is not done here.

WHAT THIS TOOL DOES NOT DO
--------------------------
It never proposes a CROSS-UNIT move.  objdiff pairs target<->base by name
WITHIN a unit (CH-3 measured -4 from 9 cross-unit moves), so a name that is
right by retail bytes and wrong by unit LOSES matches.  Every rotation here is
a permutation of labels already inside one pinned unit, which is metric-neutral
by construction on the unit membership axis.

It never SYNTHESISES a name.  Rows whose wanted method is claimed by no row in
their unit are reported as blocked, with the reason, and left alone.
"""
