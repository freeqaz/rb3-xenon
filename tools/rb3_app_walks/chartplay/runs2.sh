#!/bin/bash
# runs2.sh <K> <bin> <frames>: song-1 legs on bin-c5 (retail TrackWatcher dispatch), det, walk.txt
cd /home/free/tmp/chartplay; K=$1; B=$PWD/$2; F=${3:-9000}; W=$PWD/walk.txt
D="RB3_APP_DETERMINISTIC=1"; G="RB3_APP_JOYPAD_KIND=guitar"; R="RB3_APP_JOYPAD_KIND=drums"; C="RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1"
r() { t=$1; shift; BIN=$B SECS=900 TMO=930 ./runb.sh $K$t $W $F $D "$@" > $K$t.out 2>&1 & }
r GA $G RB3_APP_AUTOPLAY=1
r GC $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1
r DA $R RB3_APP_AUTOPLAY=1
r DC $R RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1
r GM $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_MISS=10
r DM $R RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_MISS=10
r GP $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_OFFSET_MS=80
r GN $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_OFFSET_MS=-80
r GW $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_OFFSET_MS=150
r GH $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_HOPO=tap
r GS $G RB3_APP_CHARTPLAY=1 RB3_APP_CHARTPLAY_LOG=1 RB3_APP_CHARTPLAY_SUSTAIN=0.5
wait; echo runs2 done $K
