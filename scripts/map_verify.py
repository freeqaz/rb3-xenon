#!/usr/bin/env python3
"""
map_verify.py — audit `scripts/target_symbol_map.json` entries against static
evidence, per pinned unit or tree-wide.

Why
---
Map entries generated by `tools/gen_game_target_map.py` (from the BinDiff /
rb3-Wii `unified_id_rb3wii.json` oracle) are systematically MIS-PAIRED for
small generic functions (wave-20 findings: TrackPanel `?PushCrowdReaction`
mapped onto an unrelated vtable-dispatch routine; RockCentral's mid-fuzzy band
is ~21/23 Ghidra-verified mis-pairs of trivial getters onto guard-word
thunks). Because the pre-compile `obj_target_symbol_renamer` burns the mapped
name onto the target obj's `fn_<addr>` symbol, objdiff then silently compares
our (often correct) source against the WRONG retail function — producing
fake near-zero/mid-fuzzy scores that waste porting effort.

What it checks (static evidence, no Ghidra round-trips)
-------------------------------------------------------
For every named map entry whose address falls inside a pinned unit's `.text`
ranges, cross-check the retail function at that address (via the dtk asm
`build/45410914/asm/<unit>.s` + raw bytes from `orig/45410914/band.exe`)
against our compiled obj's same-named COMDAT:

  (a) size ratio            target `.fn` size vs our COMDAT section size
  (b) referenced strings    target: read bytes at `addi ..,lbl_X+off@l`
                            addresses; base: raw bytes of `??_C@` reloc
                            targets' sections. Disjoint non-empty sets are
                            near-proof of a mis-pair; any intersection is
                            strong pro-pair evidence.
  (c) float constants       target: 4/8-byte reads at `lfs/lfd` reloc
                            addresses; base: bits from `__real@<hex>` names.
  (d) callee identity       target `bl` target addresses mapped back through
                            target_symbol_map vs base REL24 callee names.
  (e) call-count sanity     target `bl`/tail-`b` count vs base REL24 count.
  (f) opcode-shape          primary/extended-opcode multiset similarity
                            between target words and base COMDAT words
                            (catches 8-byte getters mapped to 32-byte
                            guard-word clears: zero consts either side, but
                            totally different instruction mix).

A function that report.json already scores match_percent_normalized==100 is
byte-proven and reported OK regardless of the heuristics.

Verdicts: OK / SUSPECT / MISPAIR (+ NO_BASE when our obj has no such COMDAT,
BAD_ADDR when the address is not a `.fn` start in the unit's asm). MISPAIR
requires strong negative evidence AND no positive const/callee evidence —
treat SUSPECT as "verify in Ghidra before trusting", MISPAIR as "verified
wrong by content, fix the map".

Usage
-----
  python3 scripts/map_verify.py --unit band3/bandtrack/TrackPanel   # one unit
  python3 scripts/map_verify.py --unit RockCentral
  python3 scripts/map_verify.py --all                               # tree-wide
  python3 scripts/map_verify.py --all --csv OUT.csv --summary
Options: --csv FILE (write per-entry CSV), --summary (per-unit rollup only),
--verbose (evidence detail per entry).
"""
